-- 今日できていたことを明日もできるようにする（#190）。
--
-- この列が増えるまで、admin.under18.dev の唯一のゲートは「承認されている
-- か」だけだった。承認されていれば super かどうかを問わず全部の操作が
-- できた。ここで操作ごとの細かい権限を実際に見始めると、`permissions`
-- の既定値（0、前の文で足した列定義）のままの既存の承認済み行は、
-- 今日まで出来ていたことが明日から一切できなくなる。
--
-- だから、この列が増えた時点で存在する行は全員、**super かどうかを問わず**
-- 「いま定義されている全ビット」へ合わせる。新しく承認される人は、この
-- 機能が入ったあとは 0 から始まる（最小権限）——古い行を締め出さないのと、
-- 新しい行を最小権限で始めるのは、非対称だが両方とも意図した形である。
--
-- 255 は `apps/admin-worker/src/domain/permissions.ts` の `PERMISSION_BITS`
-- （NFC_READ / NFC_WRITE / USER_READ / USER_SUSPEND / CLIENT_READ /
-- CLIENT_WRITE / AUDIT_READ / APPROVAL_GRANT の 8 個）をすべて立てた値
-- （2^8 - 1）。将来ビットを足しても、この値は過去の記録のままでよい——
-- 新しいビットを既存の行へ遡って足すかどうかは、そのときの運用判断。
--
-- 行数に依存しない。承認済みの行が何件あっても（実際は数件のはず）同じ
-- 1 文で済む。
UPDATE `admin_approvals` SET `permissions` = '255';
