/**
 * サーバーが描いた HTML と、アイランドが触る場所の継ぎ目（#332）。
 *
 * ## なぜ class で引いてはいけないのか
 *
 * アイランドは長らく `item.querySelector(".item-main")` のように
 * **見た目のクラスでサーバーの HTML を引いて**いた。4 箇所あり、
 * **どれも `?.` で繋いである。**
 *
 * つまり**一致しなくなっても例外が出ない。** 起きるのは:
 *
 *  - エラーの文言がどこにも出ない（`.item-main` が無いと append 先が無い）
 *  - 読み上げが「この項目 を削除」になる（`.item-title` が読めない）
 *  - 0 件の画面でパスキーを登録しても一覧が出ない（`p.empty` が見つからない）
 *
 * **どれも画面は壊れて見えず、型検査もテストも何も言わない。**
 *
 * ## なぜいま分けるのか
 *
 * `styles.ts` のクラスは #332 で Tailwind に替わる。**つまり
 * `.item-main` は消える。** 消えた瞬間に上の 3 つが起きるが、
 * **サーバー側のテストは緑のまま通る** —— HTML も状態コードも正しい
 * ままだからである（#320 と同じ家系）。
 *
 * 見た目のクラスは**移行のたびに変わる前提のもの**で、継ぎ目に使えない。
 * `data-*` は見た目と無関係なので、スタイルシートが何に替わっても
 * 付いてくる。
 *
 * ## なぜ定数にするのか
 *
 * 属性名を両側に直書きすると、**片方だけ直した状態**が作れる。それは
 * いま直そうとしているものそのものである。ここを 1 つにして、
 * **サーバーもアイランドも同じ文字列しか書けないようにする。**
 *
 * `test/island-hooks.test.ts` が、**画面を実際に描いて**ここの名前が
 * 出ていることを確かめている。定数を共有していても、サーバーが付け
 * 忘れれば同じことが起きるため。
 *
 * ## ここに置いてある理由
 *
 * アイランド（`client/`）は DOM の型を持つ別の tsconfig で検査される。
 * **文字列しか置かない**ので、どちらの側から読んでも問題が無い。
 * 画面の隣に置いてあるのは、**付けるのが画面の責任だから**である。
 */

/** 行の本体。エラーの文言はこの中へ足される。 */
export const ITEM_BODY_ATTR = "data-item-body";

/** 行の見出し。読み上げと確認ダイアログが「何に対する操作か」を言うのに読む。 */
export const ITEM_TITLE_ATTR = "data-item-title";

/**
 * 行に出した文言。**アイランドが作る側で、サーバーは描かない。**
 *
 * それでもここに置くのは、**作る側と引く側が同じ文字列である必要がある**
 * ため（2 回目の失敗で差し替えられずに 2 つ並ぶ）。
 */
export const ITEM_ERROR_ATTR = "data-item-error";

/**
 * 「ありません」の表示。**0 件のときだけ描かれる。**
 *
 * パスキーを登録したとき、アイランドはこれを一覧へ差し替える。
 * 見つからないと**登録は成功しているのに画面に出ない。**
 */
export const EMPTY_ATTR = "data-empty";

/**
 * 一覧。値は 0 件に戻ったときに出す文言である。
 *
 * **もともと `data-*` だった唯一の継ぎ目。** 属性名をここへ移したのは、
 * 残りと揃えて**継ぎ目の一覧が 1 箇所で読める**ようにするため。
 */
export const EMPTY_TEXT_ATTR = "data-empty-text";

/**
 * 画面が**必ず**持っていなければならない継ぎ目。
 *
 * `ITEM_ERROR_ATTR` はアイランドが作る側なので入っていない。
 */
export const SERVER_RENDERED_HOOKS = [
  ITEM_BODY_ATTR,
  ITEM_TITLE_ATTR,
  EMPTY_ATTR,
  EMPTY_TEXT_ATTR,
] as const;
