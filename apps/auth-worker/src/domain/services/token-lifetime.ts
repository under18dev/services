/**
 * トークン・セッションの有効期間（仕様書 5.3）。
 *
 * 期限の数字をコード中に散らさず、ここを単一の出典にする。
 */
export const TokenLifetime = {
  /** 認可コード: 60 秒。DB で単回交換を原子的に保証する。 */
  authorizationCodeMs: 60 * 1000,
  /** ID Token: 5 分。 */
  idTokenMs: 5 * 60 * 1000,
  /** Access Token: 10 分。 */
  accessTokenMs: 10 * 60 * 1000,
  /** ブラウザセッション: 最大 12 時間。サーバー側で失効可能。 */
  sessionMs: 12 * 60 * 60 * 1000,
  /** メール OTP: 5 分。 */
  emailOtpMs: 5 * 60 * 1000,
  /** WebAuthn Challenge: 5 分。 */
  webauthnChallengeMs: 5 * 60 * 1000,
} as const;

/** OTP の試行・再送の上限（仕様書 9 OTP）。 */
export const OtpPolicy = {
  maxAttempts: 5,

  /**
   * `resendWindowMs` の間に同じアドレス・用途へ送ってよい**再送**の回数。
   *
   * 最初の 1 通は再送ではないので、窓あたりの送信は `maxResends + 1` 通になる。
   */
  maxResends: 3,

  /**
   * 再送回数を数える窓の長さ。
   *
   * ## なぜ窓で数えるのか
   *
   * 以前は `email_challenges.resend_count` で数える設計だったが、
   * `StartEmailOtpUseCase` は送信のたびに `invalidateActive()` →`create()` で
   * **新しい行を作る**ため、カウンタは常に新しい行の 0 に戻っていた。
   * 列を進める実装（`recordResend()`）はどこからも呼ばれておらず、
   * 上限判定 `resendCount >= maxResends` は一度も真にならなかった（#88）。
   * 行を作り直す実装に合わせ、「窓の中に何行作られたか」で数える。
   *
   * ## なぜ保持期間より長くできないのか
   *
   * 数える材料は `email_challenges` の行そのものなので、**掃除された行は
   * 数えられない**。窓が `RetentionPolicy.email_challenges` を超えると、
   * 掃除を待つだけで上限を回り込める（#43 との相互作用）。この不変条件は
   * `test/otp-resend-limit.test.ts` で固定してある。
   *
   * 1 時間は保持期間と同じ値だが、**同じ判断ではない**。保持期間は
   * 「いつまで行を残すか」、ここは「どれだけ遡って数えるか」で、
   * 片方を変えてもう片方を変えない事故を上記のテストが止める。
   *
   * ## 窓あたり 4 通で足りるか
   *
   * メールが届かない利用者は 1 時間に 4 通までしか試せない。厳しいが、
   * 現状は 60 秒ごとに無制限（1 時間で 60 通）なので、迷惑行為と送信費用の
   * どちらから見ても現状のほうが悪い。経路全体のレート制限は #21 の範囲。
   */
  resendWindowMs: 60 * 60 * 1000,

  /** 再送を受け付けるまでの最短間隔。 */
  resendCooldownMs: 60 * 1000,
  codeLength: 6,

  /**
   * 用途ごとの**総量**を数える窓（#236）。
   *
   * ## なぜ 3 つ目の層が要るのか
   *
   * 既にある 2 つは、**宛先を変えながら送る攻撃で同時に外れる**:
   *
   * - `RateLimitPolicy.email_start`（IP 単位）—— IP を分ければ効かない。
   *   そのうえ Cloudflare の Rate Limiting API は近似で、本番では設定の
   *   数倍が通る（ランブック §13.2）
   * - 上の `maxResends`（アドレス単位）—— **宛先を変えれば効かない**。
   *   signup は未登録のアドレスへ送るので、宛先はいくらでも作れる
   *
   * **IP にもアドレスにも依らない層が無かった。** ここがそれで、
   * 攻撃者が IP を増やしても宛先を変えても回避できない。
   *
   * ## 窓を 1 時間より長くできない
   *
   * 数える材料が `email_challenges` の行である以上、`maxResends` と
   * まったく同じ制約が掛かる —— **掃除された行は数えられない。**
   * `RetentionPolicy.email_challenges` を超える窓にすると、掃除を待つ
   * だけで回り込める。`test/otp-resend-limit.test.ts` の不変条件に
   * この窓も含めてある。
   *
   * 1 時間で足りると判断した。この層が止めたいのは「宛先を変えながらの
   * 連続送信」で、それは 1 時間窓に必ず現れる。1 時間に数通を延々と
   * 続ける濫用は止まらないが、**それは `maxResends` が受け持つ領域**で、
   * ここに 2 つの仕事をさせると閾値がどちらの根拠でもなくなる。
   */
  globalSendWindowMs: 60 * 60 * 1000,

  /**
   * 窓あたり、用途ごとに送ってよい総数（#236）。
   *
   * ## 用途ごとに分ける理由
   *
   * **signup の枠が尽きても login は生きている**ようにする。ログインが
   * 死ぬと**既存の利用者が全員締め出される**ので、攻撃者にとってはそちらの
   * ほうが安い目標になる。signup が尽きるのは「新規登録が一時的に止まる」
   * で、被害の質がまるで違う。
   *
   * ## signup だけ桁が違う理由は、可用性の非対称だけではない
   *
   * **`signup` は、攻撃者が宛先を自由に選べて、しかも実際にメールが出る
   * 唯一の経路である。** `StartEmailOtpUseCase` のこの 1 行で条件が
   * 反転しているため:
   *
   *     const shouldSend =
   *       command.purpose === "signup" ? user === null : user?.isActive === true;
   *
   * | purpose | 攻撃者が選んだ任意のアドレスに対して |
   * | --- | --- |
   * | `login` / `verify_email` / `recovery` | アカウントが無ければ**送られない** |
   * | **`signup`** | **アカウントが無いからこそ送られる** |
   *
   * つまり `login` の 200 は**正規利用者宛の誤爆を防ぐ値**で、`signup` の
   * 30 は**無関係な第三者へ u18 からメールを送らせない値**である。
   * **性質が違うので、揃える理由が無い。**
   *
   * **「揃っていないから揃えよう」で上げないこと。** 上の反転はコードを
   * 読んだだけでは目に入らない場所にある（指摘: 94）。
   *
   * ## この層は攻撃者に「新規登録を止める」手段を与える
   *
   * 1 時間に `signup` の枠ぶん撃てば、その間は誰も登録できない。それでも
   * 入れるのは、**送信レピュテーションを失うほうが重い**からである。
   * 大量送信で弾かれるようになると、新規登録だけでなく**既存利用者の
   * ログインコードも届かなくなる。** 一時的に登録を止めるのと、全員が
   * ログインできなくなるのとでは桁が違う。
   *
   * ## 値の根拠
   *
   * いずれも「正常な利用が 1 時間でここへ届くことはない」ところに置く。
   * 届くようになったら上げる —— **閾値に達したことは監査に出る**ので
   * （`otp.start` の `global_send_cap`）、黙って詰まることはない。
   * 上げるときはランブック §13.1 も直すこと。
   */
  globalMaxSends: {
    login: 200,
    signup: 30,
    verify_email: 50,
    recovery: 50,
  },
} as const;

export const expiresAt = (now: Date, lifetimeMs: number): Date =>
  new Date(now.getTime() + lifetimeMs);
