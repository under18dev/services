/**
 * 認証が済んだあと、戻り先が無いときに着地させる場所（#15 の続き）。
 *
 * ## なぜ `/login` ではないのか
 *
 * ログインもサインアップも、**戻り先が指定されていなければ `/account` へ送る。**
 * 利用者が認証を終えた直後にやりたいのは、自分の情報を確かめるか、
 * パスキーを足すか、端末を切るかで、そのすべてがアカウント画面にある。
 * ログイン画面へ戻すと「ログイン済みです」とだけ書かれた行き止まりに
 * 着地し、**そこから次へ進む導線を利用者が自分で探すことになる。**
 *
 * `/login` のログイン済み画面そのものは消していない。ログイン済みのまま
 * `/login` を直接開いた人には今も出る。**既定の着地点でなくなっただけ。**
 *
 * ## ここが 1 か所である理由
 *
 * 着地点を決めている場所は **4 つある** —— メール OTP のログイン、
 * メール OTP のサインアップ、ログイン画面がアイランドへ渡す `data-return-to`、
 * そしてアイランド側のフォールバック（`ui/client/login-island.tsx`）。
 * 値を直接書くと、**ログインの仕方によって着地点が違う**という形で割れる。
 * パスキーで入った人だけ別の画面に着く、という壊れ方は、
 * どちらの経路も単体では動いて見えるので報告されにくい。
 *
 * ## 別の Worker へ渡ることになる
 *
 * `/account` は dashboard-worker が配信している（§14.1 決定 1 の
 * 「同一ホスト・別 Worker」）。auth-worker の中で完結していた遷移が、
 * ここで Worker の境界をまたぐ。**サインアップは以前からそうなっている**
 * ので新しく増えたリスクではないが、`/account` 側の不調がログイン直後の
 * 画面に出る、という繋がりは覚えておくこと。
 *
 * ## このファイルは何も import しない
 *
 * アイランド（ブラウザで動く唯一のファイル）がここを読むため。
 * import を足すと、その依存ごとバンドルへ入る（`island-classes` と同じ理由）。
 */

/**
 * 戻り先が無いときの着地点。
 *
 * `sanitizeReturnTo` の許可リスト（`ui/return-to.ts`）に含まれていること。
 * ここだけ別の場所を指すと、「戻り先として渡すと弾かれるが、既定では行く」
 * という食い違いができる。
 */
export const DEFAULT_LANDING_PATH = "/account";
